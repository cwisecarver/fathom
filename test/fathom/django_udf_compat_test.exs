  setup context do
    path = Path.join(System.tmp_dir!(), "fathom_udf_#{System.unique_integer([:positive])}.db")
    opts = Map.get(context, :open_opts, [])
    {:ok, conn} = Connection.open(path, opts)

    on_exit(fn ->
      Connection.close(conn)
      for s <- ["", "-wal", "-shm"], do: File.rm(path <> s)
    end)

    %{conn: conn, path: path}
  end

  defp one(conn, sql) do
    case Connection.query(conn, sql, []) do
      {:ok, %{rows: [[value] | _]}} -> value
      {:ok, %{rows: []}} -> :no_rows
      {:error, reason} -> {:error, reason}
    end
  end

  defp available?(conn, sql) do
    case Connection.query(conn, sql, []) do
      {:ok, _} -> true
      {:error, reason} -> not (inspect(reason) =~ "no such function")
    end
  end

