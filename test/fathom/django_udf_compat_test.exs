defmodule Fathom.DjangoUdfCompatTest do
  @moduledoc """
  Expert review 2026-08-01 **#19**: Django's SQLite backend registers ~35 Python UDFs on every
  *client* connection. Under `django-libsql` the SQL crosses the wire and is compiled by
  **fathom's** SQLite, where those functions did not exist — so ordinary querysets
  (`__year`, `__date`, `__regex`, `Trunc*`, `F()` arithmetic on a `DurationField`) raised
  `OperationalError` against the flagship "point an unchanged Django app at it" claim, while basic
  CRUD worked. That asymmetry is exactly why the working slice and both TPC harnesses never caught
  it: TPC-B and TPC-C use only builtins.

  **This file used to be the tracked list of what was MISSING. As of 2026-08-05 it is the
  behavioural suite for what is SUPPLIED.** All 54 functions Django needs now resolve: 19 from
  SQLite's own `SQLITE_ENABLE_MATH_FUNCTIONS` build, and 35 from `fathom_udf`, the Rust loadable
  extension in `native/fathom_udf` (see `Fathom.Shard.Extension` for the load-and-relock sequence
  and `docs/quickstart-django.md` for the operator view).

  ## What is tested WHERE, and why it is split

  This file drives the functions **over the real connection path** — `Fathom.Shard.Connection`,
  the same code a Hrana stream uses — so it covers the wiring: that the extension loads, that it
  loads on tenant and read-only handles too, and that results survive the round trip as the right
  SQLite type. It asserts a representative result per family rather than exhaustive values.

  Exhaustive value-level agreement with Django lives in the Rust crate, where
  `native/fathom_udf/tests/oracle.rs` replays **12,501 cases generated by running Django's own
  `_sqlite_*` functions** (`tests/oracle/generate_cases.py`). That is the right place for it: it
  needs no database, runs in milliseconds, and its expectations are generated rather than
  hand-written. Seven real bugs came out of it that hand-written expectations had missed —
  including `django_format_dtdelta` returning text where Django returns a number, and
  `date - timedelta` moving the date a day when it should not.

  Duplicating that matrix here would be slower, no more correct, and a second place to update.
  """
  use ExUnit.Case, async: false

  alias Fathom.Shard.Connection
  alias Fathom.Shard.Extension

